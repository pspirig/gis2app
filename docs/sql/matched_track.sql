-- =====================================================================
-- Tabelle matched_track: auf das OSM-Fussnetz gematchte Wege
-- Ausführen in pgAdmin → Query Tool.
-- Wird vom Backend befüllt (Flask, /map_match/<track_id>), nicht von der App.
--
-- Eine Zeile pro Weg (UNIQUE track_id). Wird ein Weg nochmals gematcht,
-- überschreibt das Backend den alten Eintrag.
-- matched_fraction = Anteil der GPS-Punkte, die gematcht werden konnten (0–1).
-- Wege mit einem Wert unter 1 sind nur teilweise gematcht.
-- =====================================================================

CREATE TABLE gta26_g1.matched_track (
    matchedtrack_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    track_id         integer UNIQUE REFERENCES gta26_g1.actual_track (track_id),
    geometry         geometry,
    length           real,
    matched_fraction real,
    calculated_at    timestamp with time zone DEFAULT now()
);
