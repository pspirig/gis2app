-- =====================================================================
-- IDs automatisch von der Datenbank vergeben lassen (Punkt 10)
-- Ausführen in pgAdmin → Query Tool, Schritt für Schritt.
-- Ändert NUR die ID-Spalten. Tabellen, Daten und GeoServer-Layer bleiben.
-- =====================================================================


-- ---------------------------------------------------------------------
-- Schritt 1: Prüfen, ob die IDs schon automatisch vergeben werden
-- ---------------------------------------------------------------------
-- Pro ID-Spalte gilt: automatisch, wenn
--   is_identity = 'YES'                     ODER
--   column_default beginnt mit 'nextval('   (= serial)
-- Wenn beides fehlt → Schritt 2 für diese Tabelle ausführen.

SELECT table_name, column_name, column_default, is_identity
FROM information_schema.columns
WHERE table_schema = 'gta26_g1'
  AND column_name IN ('user_id', 'track_id', 'unsafe_point_id', 'shortestpath_id', 'analysis_id')
  AND (table_name, column_name) IN (
        ('user', 'user_id'),
        ('actual_track', 'track_id'),
        ('unsafe_point', 'unsafe_point_id'),
        ('shortest_path', 'shortestpath_id'),
        ('routeanalysis', 'analysis_id')
  );


-- ---------------------------------------------------------------------
-- Schritt 2: Automatische IDs einschalten (nur wo nötig!)
-- ---------------------------------------------------------------------
-- Jeweils zwei Befehle pro Tabelle:
--   1. Spalte zählt ab jetzt selbst hoch
--   2. Zähler hinter die grösste vorhandene ID setzen (falls schon Testdaten drin sind)
-- Hinweis: «user» ist ein reserviertes Wort, darum dort in Anführungszeichen.

-- user
ALTER TABLE gta26_g1."user" ALTER COLUMN user_id ADD GENERATED BY DEFAULT AS IDENTITY;
SELECT setval(pg_get_serial_sequence('gta26_g1."user"', 'user_id'),
              COALESCE((SELECT MAX(user_id) FROM gta26_g1."user"), 0) + 1, false);

-- actual_track
ALTER TABLE gta26_g1.actual_track ALTER COLUMN track_id ADD GENERATED BY DEFAULT AS IDENTITY;
SELECT setval(pg_get_serial_sequence('gta26_g1.actual_track', 'track_id'),
              COALESCE((SELECT MAX(track_id) FROM gta26_g1.actual_track), 0) + 1, false);

-- unsafe_point
ALTER TABLE gta26_g1.unsafe_point ALTER COLUMN unsafe_point_id ADD GENERATED BY DEFAULT AS IDENTITY;
SELECT setval(pg_get_serial_sequence('gta26_g1.unsafe_point', 'unsafe_point_id'),
              COALESCE((SELECT MAX(unsafe_point_id) FROM gta26_g1.unsafe_point), 0) + 1, false);

-- shortest_path (wird später von der Analyse befüllt)
ALTER TABLE gta26_g1.shortest_path ALTER COLUMN shortestpath_id ADD GENERATED BY DEFAULT AS IDENTITY;
SELECT setval(pg_get_serial_sequence('gta26_g1.shortest_path', 'shortestpath_id'),
              COALESCE((SELECT MAX(shortestpath_id) FROM gta26_g1.shortest_path), 0) + 1, false);

-- routeanalysis (wird später von der Analyse befüllt)
ALTER TABLE gta26_g1.routeanalysis ALTER COLUMN analysis_id ADD GENERATED BY DEFAULT AS IDENTITY;
SELECT setval(pg_get_serial_sequence('gta26_g1.routeanalysis', 'analysis_id'),
              COALESCE((SELECT MAX(analysis_id) FROM gta26_g1.routeanalysis), 0) + 1, false);


-- ---------------------------------------------------------------------
-- Schritt 3: Weitere Pflichtfelder prüfen
-- ---------------------------------------------------------------------
-- Spalten mit is_nullable = 'NO' und ohne column_default MÜSSEN beim Speichern
-- einen Wert bekommen. Die App schickt z. B. kein «tackingactive».
-- Steht hier ausser den ID-Spalten etwas, bitte melden.

SELECT table_name, column_name, data_type
FROM information_schema.columns
WHERE table_schema = 'gta26_g1'
  AND table_name IN ('user', 'actual_track', 'unsafe_point')
  AND is_nullable = 'NO'
  AND column_default IS NULL
  AND is_identity = 'NO';
